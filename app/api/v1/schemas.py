"""API request and response schemas conforming to OpenAI-compatible Chat API specifications.

Implements Pydantic v2 models for chat completions, streaming chunks, health checks,
and structured error representations.
"""

import time
from typing import Literal

from pydantic import BaseModel, Field


class ChatMessage(BaseModel):
    """A single message within a chat conversation.

    Attributes:
        role: The role of the author ('system', 'user', or 'assistant').
        content: The text content of the message.
    """

    role: Literal["system", "user", "assistant"] = Field(
        ...,
        description="The role of the messages author: system, user, or assistant.",
    )
    content: str = Field(
        ...,
        description="The contents of the message.",
    )


class ChatCompletionRequest(BaseModel):
    """Request payload for chat completion endpoints.

    Attributes:
        messages: List of conversation messages forming the prompt context.
        model: Target model identifier or alias (e.g. 'gpt-4o', 'gemini-1.5-pro').
        temperature: Sampling temperature between 0.0 and 2.0. Higher values mean more random.
        max_tokens: Maximum number of tokens to generate in the completion.
        stream: Whether to stream back partial progress using Server-Sent Events (SSE).
        provider: Optional explicit provider override ('mock', 'openai', 'anthropic', 'gemini').
        user: Optional unique identifier representing end-user or tenant for rate limiting.
    """

    messages: list[ChatMessage] = Field(
        ...,
        min_length=1,
        description="A list of messages comprising the conversation so far.",
    )
    model: str | None = Field(
        default=None,
        description="ID of the model to use. If not specified, default proxy model is used.",
    )
    temperature: float = Field(
        default=0.7,
        ge=0.0,
        le=2.0,
        description="What sampling temperature to use, between 0.0 and 2.0.",
    )
    max_tokens: int = Field(
        default=1024,
        ge=1,
        le=128000,
        description="The maximum number of tokens to generate in the chat completion.",
    )
    stream: bool = Field(
        default=False,
        description="If set, partial message deltas will be sent like in ChatGPT.",
    )
    provider: str | None = Field(
        default=None,
        description="Optional upstream provider override.",
    )
    user: str | None = Field(
        default=None,
        description="A unique identifier representing your end-user.",
    )


class DeltaContent(BaseModel):
    """Delta message content yielded in streaming chunks.

    Attributes:
        role: Author role if introduced in this chunk.
        content: Incremental text content generated.
    """

    role: str | None = Field(
        default=None,
        description="The role of the author of this message chunk.",
    )
    content: str | None = Field(
        default=None,
        description="The partial message text content.",
    )


class Choice(BaseModel):
    """Choice generated by the model in response to the chat completion request.

    Attributes:
        index: Index of the choice in the response list.
        delta: Incremental delta chunk (present during streaming).
        message: Complete generated message (present in non-streaming response).
        finish_reason: Reason the model stopped generating tokens ('stop', 'length', etc.).
    """

    index: int = Field(
        default=0,
        description="The index of the choice in the list of choices.",
    )
    delta: DeltaContent | None = Field(
        default=None,
        description="A chat completion delta generated by streamed model responses.",
    )
    message: ChatMessage | None = Field(
        default=None,
        description="A chat completion message generated by the model.",
    )
    finish_reason: str | None = Field(
        default=None,
        description="The reason the model stopped generating tokens.",
    )


class UsageInfo(BaseModel):
    """Token usage statistics for the completion request.

    Attributes:
        prompt_tokens: Number of tokens in the prompt context.
        completion_tokens: Number of tokens generated in the completion.
        total_tokens: Total tokens consumed (prompt + completion).
    """

    prompt_tokens: int = Field(
        default=0,
        description="Number of tokens in the prompt.",
    )
    completion_tokens: int = Field(
        default=0,
        description="Number of tokens in the generated completion.",
    )
    total_tokens: int = Field(
        default=0,
        description="Total number of tokens used in the request (prompt + completion).",
    )


class ChatCompletionResponse(BaseModel):
    """Non-streaming response returned for chat completion requests.

    Attributes:
        id: Unique request / completion identifier.
        object: String identifier for object type ('chat.completion').
        created: Unix timestamp (seconds) when the response was created.
        choices: List of generated completion choices.
        model: Identifier of the model that generated the completion.
        usage: Token usage statistics.
        cached: Boolean indicating if response was served from semantic cache.
    """

    id: str = Field(
        ...,
        description="A unique identifier for the chat completion.",
    )
    object: str = Field(
        default="chat.completion",
        description="The object type, which is always 'chat.completion'.",
    )
    created: int = Field(
        default_factory=lambda: int(time.time()),
        description="The Unix timestamp (in seconds) of when the chat completion was created.",
    )
    choices: list[Choice] = Field(
        ...,
        description="A list of chat completion choices.",
    )
    model: str = Field(
        ...,
        description="The model used for the chat completion.",
    )
    usage: UsageInfo | None = Field(
        default=None,
        description="Usage statistics for the completion request.",
    )
    cached: bool = Field(
        default=False,
        description="Indicates whether this response was retrieved from semantic cache.",
    )


class ChatCompletionChunk(BaseModel):
    """Chunk of streaming response conforming to OpenAI SSE format.

    Attributes:
        id: Unique completion identifier.
        object: String identifier for chunk type ('chat.completion.chunk').
        created: Unix timestamp (seconds) when chunk was emitted.
        choices: List of choice deltas.
        model: Identifier of the model generating tokens.
    """

    id: str = Field(
        ...,
        description="A unique identifier for the chat completion chunk.",
    )
    object: str = Field(
        default="chat.completion.chunk",
        description="The object type, which is always 'chat.completion.chunk'.",
    )
    created: int = Field(
        default_factory=lambda: int(time.time()),
        description="The Unix timestamp (in seconds) of when the chunk was created.",
    )
    choices: list[Choice] = Field(
        ...,
        description="A list of chat completion chunk choices.",
    )
    model: str = Field(
        ...,
        description="The model used to generate the chunk.",
    )


class HealthResponse(BaseModel):
    """Health check endpoint status response.

    Attributes:
        status: Overall proxy service health status ('healthy', 'degraded', etc.).
        redis: Status of Redis connectivity ('connected', 'disconnected', etc.).
        version: Application software version.
    """

    status: str = Field(
        ...,
        description="Overall service health status.",
    )
    redis: str = Field(
        ...,
        description="Redis connection status.",
    )
    version: str = Field(
        ...,
        description="Application version.",
    )


class ErrorResponse(BaseModel):
    """Standardized error response payload.

    Attributes:
        error: High-level error summary or exception type.
        detail: Detailed error explanation or guidance.
        code: Optional machine-readable error code.
    """

    error: str = Field(
        ...,
        description="High-level error description.",
    )
    detail: str | None = Field(
        default=None,
        description="Detailed context or traceback info if in debug mode.",
    )
    code: str | None = Field(
        default=None,
        description="Machine-readable error identifier.",
    )
